def pod(id_, level, title, hu, desc, cast, lines, questions, vocab):
    return {"id": id_, "level": level, "title": title, "hu": hu, "desc": desc, "cast": cast,
            "lines": [{"s": s, "it": t, "hu": h} for s, t, h in lines],
            "questions": [{"q": q, "o": o, "a": 0} for q, o in questions],
            "vocab": [{"it": a, "hu": b} for a, b in vocab]}

def pack(id_, title, desc, items):
    return {"id": id_, "title": title, "desc": desc, "items": [{"it": a, "hu": b, "ex": c, "exhu": d} for a, b, c, d in items]}

